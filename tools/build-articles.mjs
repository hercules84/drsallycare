// Generates the guides hub (/learn/), one static page per article, assets/articles-data.js and sitemap.xml
// from tools/articles.json.   Run:  node tools/build-articles.mjs   (no dependencies, no Cloudflare build step)
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const articles = JSON.parse(fs.readFileSync(path.join(root, "tools/articles.json"), "utf8"));
const DATE = "2026-10-08";
const V = "26"; // asset version, must match the ?v= used in the other pages

const TAGKEY = { autism:"tagAutism", adhd:"tagAdhd", adolescence:"tagAdolescence", learning:"tagLearning",
  teachers:"tagTeachers", community:"tagCommunity", wellbeing:"tagWellbeing", consultation:"tagConsultation" };

const esc = s => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const js = o => JSON.stringify(o).replace(/<\/(script)/gi, "<\\/$1").replace(/[\u2028\u2029]/g, "");

function head({ title, desc, url, extra = "" }) {
  return `<!doctype html>
<html lang="ar" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${esc(title)}</title>
<link rel="canonical" href="https://drsallycare.com${url}">
<meta name="description" content="${esc(desc)}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="Dr. Sally Rizqo">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="https://drsallycare.com${url}">
<meta property="og:image" content="https://drsallycare.com/icon-512.png">
<meta name="theme-color" content="#3F729B">
<link rel="icon" href="/favicon.ico"><link rel="apple-touch-icon" href="/apple-touch-icon.png">
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Vazirmatn:wght@400;500;700;800&family=Fraunces:opsz,wght@9..144,600;9..144,700&family=Nunito+Sans:wght@400;600;700&display=swap">
<link rel="stylesheet" href="/assets/site.css?v=${V}">
${extra}</head>
<body>
`;
}

// ---------- data file used by the hub and the home page ----------
const data = articles.map(a => ({ slug: a.slug, topic: a.topic, min: a.min,
  ar: { title: a.ar.title, sum: a.ar.sum }, en: { title: a.en.title, sum: a.en.sum } }));
fs.writeFileSync(path.join(root, "assets/articles-data.js"),
  "/* generated by tools/build-articles.mjs — edit tools/articles.json instead */\nwindow.ARTICLES = " + js(data) + ";\n");

// shared card renderer (also used on the home page): text from ARTICLES + tx()
fs.writeFileSync(path.join(root, "assets/articles-ui.js"), `/* Renders article cards. Needs window.ARTICLES (articles-data.js) and window.tx / window.getLang (site.js). */
(function(){
  const TAG = ${js(TAGKEY)};
  window.artCard = function(a){
    const L = window.getLang(), d = a[L] || a.ar;
    const kuAr = L === "ku" ? " lang=\\"ar\\"" : "";
    return '<a class="art-card" href="/learn/' + a.slug + '/" data-topic="' + a.topic + '"><span class="art-tag">' + window.tx(TAG[a.topic]) +
      '</span><h3' + kuAr + '>' + d.title + '</h3><p' + kuAr + '>' + d.sum + '</p><span class="art-min">' + a.min + ' ' + window.tx("minWord") + '</span></a>';
  };
  window.artTag = t => window.tx(TAG[t]);
})();
`);

// ---------- one page per article ----------
for (const a of articles) {
  const dir = path.join(root, "learn", a.slug);
  fs.mkdirSync(dir, { recursive: true });
  const url = `/learn/${a.slug}/`;
  const ld = {
    "@context": "https://schema.org", "@type": "Article",
    headline: a.en.title, description: a.en.sum, inLanguage: ["ar", "ku", "en"],
    datePublished: DATE, dateModified: DATE, mainEntityOfPage: "https://drsallycare.com" + url,
    publisher: { "@type": "Organization", name: "Dr. Sally Rizqo", url: "https://drsallycare.com/" }
  };
  const t = {
    ar: { pageTitle: a.ar.title + " | د. سالي رزقو", title: a.ar.title, sum: a.ar.sum, body: a.ar.body },
    en: { pageTitle: a.en.title + " | Dr. Sally Rizqo", title: a.en.title, sum: a.en.sum, body: a.en.body }
  };
  const html = head({ title: a.ar.title + " | د. سالي رزقو | Dr. Sally Rizqo", desc: a.en.sum, url,
      extra: `<script type="application/ld+json">${js(ld)}</script>\n` }) + `<main class="wrap article" id="art">
  <a class="back" href="/learn/" data-i18n="backLearn"></a>
  <span class="art-tag" id="tag"></span>
  <h1 data-i18n="title"></h1>
  <p class="lead" data-i18n="sum"></p>
  <div class="ku-note lang-note" hidden></div>
  <div class="card prose" data-i18n="body"></div>
  <p class="small-note" data-i18n="artNote"></p>
  <section class="cta">
    <h2 data-i18n="ctaTitle"></h2><p class="lead" data-i18n="ctaLead"></p>
    <div class="btns"><a class="btn primary wa-link" href="/#book"><span data-i18n="btnBook"></span></a></div>
  </section>
  <section style="padding-top:8px"><h2 data-i18n="moreArt"></h2><div class="art-grid" id="more"></div></section>
</main>
<script src="/assets/articles-data.js?v=${V}"></script>
<script>
window.PAGE = { id:"learn", t:${js(t)},
 onLang(){
  document.getElementById("tag").textContent = window.artTag(${js(a.topic)});
  const others = window.ARTICLES.filter(x => x.slug !== ${js(a.slug)});
  others.sort((x, y) => (y.topic === ${js(a.topic)}) - (x.topic === ${js(a.topic)}));
  document.getElementById("more").innerHTML = others.slice(0, 3).map(window.artCard).join("");
 } };
</script>
<script src="/assets/articles-ui.js?v=${V}"></script>
<script src="/assets/site.js?v=${V}"></script>
</body>
</html>
`;
  fs.writeFileSync(path.join(dir, "index.html"), html);
}

// ---------- hub ----------
fs.mkdirSync(path.join(root, "learn"), { recursive: true });
const hubT = {
  ar: { pageTitle: "مقالات وأدلة للأهل والمعلمين | د. سالي رزقو", title: "مقالات وأدلة", lead: "معلومات عملية ومبسّطة للأهل والمعلمين حول التوحد وفرط الحركة وتشتت الانتباه وصعوبات التعلم والمراهقة ودعم الأطفال في الأزمات." },
  ku: { pageTitle: "ڕێبەر و بابەتێن بۆ خێزان و مامۆستایان | د. سالی ڕزقۆ", title: "ڕێبەر و بابەت", lead: "زانیاریێن کرداری و ساناهی بۆ خێزان و مامۆستایان دەربارەی ئۆتیزم، زێدە-جوولە، زەحمەتیێن فێربوونێ، هەرزەکاری و پشتەڤانیا زارۆکان د قەیرانان دا." },
  en: { pageTitle: "Guides & articles for families and teachers | Dr. Sally Rizqo", title: "Guides & articles", lead: "Practical, plain-language information for families and teachers on autism, ADHD, learning difficulties, adolescence and supporting children in crises." }
};
const hubLd = { "@context": "https://schema.org", "@type": "CollectionPage", name: "Guides & articles", url: "https://drsallycare.com/learn/", inLanguage: ["ar", "ku", "en"] };
fs.writeFileSync(path.join(root, "learn/index.html"), head({
  title: "مقالات وأدلة | د. سالي رزقو | Dr. Sally Rizqo",
  desc: "Practical guides for families and teachers on autism, ADHD, learning difficulties, adolescence and children under stress. Arabic, Kurdish, English.",
  url: "/learn/", extra: `<script type="application/ld+json">${js(hubLd)}</script>\n` }) + `<main class="wrap" id="hub">
  <section class="topic-hero" style="--c:var(--teal);--cs:var(--teal-soft)">
    <div><h1 data-i18n="title"></h1><p class="lead" data-i18n="lead"></p></div>
  </section>
  <div class="chips" id="chips" role="group"></div>
  <div class="art-grid" id="grid"></div>
  <section class="cta">
    <h2 data-i18n="ctaTitle"></h2><p class="lead" data-i18n="ctaLead"></p>
    <div class="btns"><a class="btn primary wa-link" href="/#book"><span data-i18n="btnBook"></span></a></div>
  </section>
</main>
<script src="/assets/articles-data.js?v=${V}"></script>
<script>
(function(){
 let cur = "all";
 const topics = ["all", ...Array.from(new Set(window.ARTICLES.map(a => a.topic)))];
 function draw(){
  const key = { all:"allTags", autism:"tagAutism", adhd:"tagAdhd", adolescence:"tagAdolescence", learning:"tagLearning", teachers:"tagTeachers", community:"tagCommunity", wellbeing:"tagWellbeing", consultation:"tagConsultation" };
  document.getElementById("chips").innerHTML = topics.map(t => '<button type="button" data-t="' + t + '" aria-pressed="' + (t === cur) + '">' + window.tx(key[t]) + '</button>').join("");
  document.getElementById("grid").innerHTML = window.ARTICLES.filter(a => cur === "all" || a.topic === cur).map(window.artCard).join("");
  document.querySelectorAll("#chips button").forEach(b => b.onclick = () => { cur = b.dataset.t; draw(); });
 }
 window.PAGE = { id:"learn", t:${js(hubT)}, onLang: draw };
})();
</script>
<script src="/assets/articles-ui.js?v=${V}"></script>
<script src="/assets/site.js?v=${V}"></script>
</body>
</html>
`);

// ---------- languages, hreflang and sitemap (tools/build-langs.mjs) ----------
await import("./build-langs.mjs");
